//! Direct Anthropic API integration for the free-text brief feature.
//!
//! Deliberately not in `vibecut-ops`: the MCP transport never
//! calls an LLM itself — "the LLM lives in the client" is the whole
//! architectural premise there (see README's Architecture section). A
//! browser client has no LLM built in the way Claude Desktop does, so
//! the web UI is the one transport that legitimately needs to make
//! this call itself, which is why it lives here instead.
//!
//! The API key is read from the `ANTHROPIC_API_KEY` environment
//! variable on the `vibecut-web` process — never accepted from the
//! browser. A secret that round-trips through client-side JS to reach
//! a server is a secret visible in the network tab; reading it
//! server-side from the process environment is both simpler and the
//! only defensible choice here.

use serde::de::DeserializeOwned;
use serde_json::json;
use vibecut_ops::error::OpsError;

const ANTHROPIC_API_URL: &str = "https://api.anthropic.com/v1/messages";
const ANTHROPIC_VERSION: &str = "2023-06-01";
const DEFAULT_MODEL: &str = "claude-sonnet-5";

fn api_key() -> Result<String, OpsError> {
    std::env::var("ANTHROPIC_API_KEY").map_err(|_| {
        OpsError::internal(
            "ANTHROPIC_API_KEY not set on the vibecut-web process — set it and restart \
             the server to use the free-text brief feature",
        )
    })
}

fn model() -> String {
    std::env::var("VIBECUT_LLM_MODEL").unwrap_or_else(|_| DEFAULT_MODEL.to_string())
}

/// Send one forced-tool-use request to the Messages API and
/// deserialize the tool call's `input` as `T`. `tool_schema` must be a
/// complete JSON Schema object — see [`vibecut_ops::feedback::feedback_pick_json_schema`]
/// for why a schema generated by one `schemars::schema_for!` call
/// (rather than composed by hand from smaller pieces) is the shape
/// this expects.
pub async fn call_tool<T: DeserializeOwned>(
    system_prompt: &str,
    user_message: &str,
    tool_name: &str,
    tool_description: &str,
    tool_schema: serde_json::Value,
) -> Result<T, OpsError> {
    let key = api_key()?;
    let body = json!({
        "model": model(),
        "max_tokens": 1024,
        "system": system_prompt,
        "messages": [{"role": "user", "content": user_message}],
        "tools": [{
            "name": tool_name,
            "description": tool_description,
            "input_schema": tool_schema,
        }],
        "tool_choice": {"type": "tool", "name": tool_name},
    });

    let client = reqwest::Client::new();
    let resp = client
        .post(ANTHROPIC_API_URL)
        .header("x-api-key", key)
        .header("anthropic-version", ANTHROPIC_VERSION)
        .json(&body)
        .send()
        .await
        .map_err(|e| OpsError::internal(format!("Anthropic API request failed: {e}")))?;

    let status = resp.status();
    let value: serde_json::Value = resp
        .json()
        .await
        .map_err(|e| OpsError::internal(format!("Anthropic API returned a non-JSON response: {e}")))?;

    if !status.is_success() {
        let msg = value
            .get("error")
            .and_then(|e| e.get("message"))
            .and_then(|m| m.as_str())
            .unwrap_or("(no error message in response body)");
        return Err(OpsError::internal(format!(
            "Anthropic API error ({status}): {msg}"
        )));
    }

    let tool_input = extract_tool_input(&value).ok_or_else(|| {
        OpsError::internal("Anthropic API response had no tool_use content block".to_string())
    })?;

    serde_json::from_value(tool_input.clone())
        .map_err(|e| OpsError::internal(format!("could not parse the model's tool input: {e}")))
}

/// Pull the first `tool_use` block's `input` out of a Messages API
/// response body. Split out from [`call_tool`] so it's testable
/// without a network call — fixture in, `Option<&Value>` out.
fn extract_tool_input(response: &serde_json::Value) -> Option<&serde_json::Value> {
    response
        .get("content")?
        .as_array()?
        .iter()
        .find(|b| b.get("type").and_then(|t| t.as_str()) == Some("tool_use"))?
        .get("input")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Only asserts when the env var genuinely isn't set, which is
    /// the state of every host that hasn't opted in — reading (never
    /// setting) an env var in a test is safe under parallel test
    /// execution; nothing here mutates process state.
    #[test]
    fn api_key_missing_is_a_clear_error() {
        if std::env::var("ANTHROPIC_API_KEY").is_err() {
            let err = api_key().unwrap_err();
            assert!(matches!(err, OpsError::Internal(_)));
        }
    }

    #[test]
    fn extract_tool_input_finds_the_tool_use_block() {
        let response = json!({
            "content": [
                {"type": "text", "text": "thinking out loud"},
                {"type": "tool_use", "id": "toolu_1", "name": "pick_vibe", "input": {"vibe": "kid_reel", "rationale": "active kid footage"}}
            ]
        });
        let input = extract_tool_input(&response).expect("tool_use block present");
        assert_eq!(input["vibe"], "kid_reel");
    }

    #[test]
    fn extract_tool_input_none_when_absent() {
        let response = json!({ "content": [{"type": "text", "text": "no tool call here"}] });
        assert!(extract_tool_input(&response).is_none());
    }
}
